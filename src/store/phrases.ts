/** Возвращает случайную фразу, стараясь не повторять предыдущую */
export function pickMotivationPhrase(previous?: string): string {
  try {
    if (MOTIVATION_PHRASES.length === 0) {
      return 'Вперёд.';
    }
    if (MOTIVATION_PHRASES.length === 1) {
      return MOTIVATION_PHRASES[0];
    }
    let next =
      MOTIVATION_PHRASES[Math.floor(Math.random() * MOTIVATION_PHRASES.length)];
    let guard = 0;
    while (next === previous && guard < 12) {
      next =
        MOTIVATION_PHRASES[Math.floor(Math.random() * MOTIVATION_PHRASES.length)];
      guard += 1;
    }
    return next;
  } catch {
    return 'Вперёд.';
  }
}
